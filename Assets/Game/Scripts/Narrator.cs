    /// <summary>Narration subtitles on/off toggle.</summary>
    public static bool showNarrationSubtitles = true;

    /// <summary>
    /// Play the recordings in Resources/Narration (generated by Tools/Narration/generate_voices.py: re-run it after
    /// changing a line above). Off: lines are subtitles only (shown long enough to read).
    /// </summary>
    public static bool useRecordedVoice = true;

    /// <summary>Stage 1 lines that hold the player in place (can still look around) while they play.</summary>
    public static readonly HashSet<string> FreezeLines = new HashSet<string>
    {
        "N1_01", // the opening torch instruction
    };

    /// <summary>Say a line once per playthrough (ignored if already said or if it belongs to an earlier stage).</summary>
    public static void SayOnce(string id)
    {
        if (string.IsNullOrEmpty(id) || IsStale(id) || !Instance.m_Said.Add(id))
            return;
        Instance.Enqueue(id);
    }

    /// <summary>Say a line even if it was said before.</summary>
    public static void Say(string id)
    {
        if (!string.IsNullOrEmpty(id) && !IsStale(id))
            Instance.Enqueue(id);
    }

    /// <summary>Call after the stage changes: drops queued lines from earlier stages and cuts one that's playing.</summary>
    public static void OnStageChanged()
    {
        var n = Instance;
        var keep = new List<string>(n.m_Queue);
        n.m_Queue.Clear();
        foreach (var id in keep)
            if (!IsStale(id))
                n.m_Queue.Enqueue(id);
        if (n.m_Current != null && IsStale(n.m_Current))
            n.m_Cut = true;
        n.SetMovementLock(false);
    }

    /// <summary>"N2_04" → 2. Lines without a stage prefix (CAUGHT, hints) → 0.</summary>
    static int StageOf(string id)
    {
        if (id.Length > 2 && id[0] == 'N' && char.IsDigit(id[1]) && id[2] == '_')
            return id[1] - '0';
        return 0;
    }

    static int CurrentStage => GameFlow.Instance != null ? GameFlow.Instance.CurrentStage : 1;

    static bool IsStale(string id)
    {
        var s = StageOf(id);
        return s > 0 && s < CurrentStage;
    }

    /// <summary>Shows a short hint as a subtitle without any voice (e.g. "It's locked").</summary>
    public static void Hint(string text) => Instance.StartCoroutine(Instance.ShowHint(text));

    readonly HashSet<string> m_Said = new HashSet<string>();
    readonly Queue<string> m_Queue = new Queue<string>();
    bool m_Busy;

    void Awake()
    {
        if (s_Instance != null && s_Instance != this) { Destroy(gameObject); return; }
        s_Instance = this;
    }

    void Enqueue(string id)
    {
        m_Queue.Enqueue(id);
        if (!m_Busy)
            StartCoroutine(Run());
    }

    /// <summary>Sets up the audio source and subtitle text mesh following the player head.</summary>
    void Setup()
    {
        var head = PlayerRig.Head;
        if (head == null || m_Audio != null)
            return;

        // Walkie-talkie on the player's hip, filtered to sound like a radio.
        var radio = new GameObject("Walkie-Talkie Voice");
        radio.transform.SetParent(head, false);
        radio.transform.localPosition = new Vector3(0.15f, -0.6f, 0.05f);
        m_Audio = radio.AddComponent<AudioSource>();
        m_Audio.spatialBlend = 0.6f;
        m_Audio.playOnAwake = false;
        radio.AddComponent<AudioHighPassFilter>().cutoffFrequency = 300f;
        radio.AddComponent<AudioLowPassFilter>().cutoffFrequency = 3000f;

        // Subtitle on the right forearm, like a watch (see PlaceSubtitle). Built at its size 1 m from the eyes;
        // the root's scale sets the real size.
        m_SubtitleRoot = new GameObject("Subtitle Root").transform;
        m_SubtitleRoot.SetParent(head.parent, false);
        var sub = new GameObject("Subtitle");
        sub.transform.SetParent(m_SubtitleRoot, false);
        m_Subtitle = sub.AddComponent<TextMesh>();
        Font font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        m_Subtitle.font = font;
        // Drawn on top of walls, and above the screen fade (4000) so lines over a black screen stay readable.
        sub.GetComponent<MeshRenderer>().sharedMaterial = OverlayTextMaterial(font, 4100);
        m_Subtitle.fontSize = 200;
        m_Subtitle.characterSize = 0.0032f;
        m_Subtitle.anchor = TextAnchor.MiddleCenter;
        m_Subtitle.alignment = TextAlignment.Center;
        m_Subtitle.color = new Color(0.95f, 0.88f, 0.65f);
        m_Subtitle.text = "";

        // Cinematic dark strip behind the text — renders before the font (queue 2950 < 3000).
        var strip = GameObject.CreatePrimitive(PrimitiveType.Quad);
        strip.name = "Subtitle Strip";
        Destroy(strip.GetComponent<Collider>());
        strip.transform.SetParent(m_SubtitleRoot, false);
        strip.transform.localPosition = new Vector3(0f, 0f, 0.006f); // just behind the text
        strip.transform.localScale    = new Vector3(k_StripWidth, 0.068f, 1f);
        var stripMat = new Material(Shader.Find("Universal Render Pipeline/Unlit") ?? Shader.Find("Unlit/Color"));
        stripMat.SetInt("_SrcBlend", (int)UnityEngine.Rendering.BlendMode.SrcAlpha);
        stripMat.SetInt("_DstBlend", (int)UnityEngine.Rendering.BlendMode.OneMinusSrcAlpha);
        stripMat.SetInt("_ZWrite",   0);
        stripMat.SetInt("_ZTest",    (int)UnityEngine.Rendering.CompareFunction.Always);
        stripMat.SetFloat("_Surface", 1f);
        stripMat.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
        stripMat.SetOverrideTag("RenderType", "Transparent");
        stripMat.renderQueue = 4090;
        stripMat.SetColor("_BaseColor", new Color(0.04f, 0.02f, 0.01f, 0f)); // starts invisible
        if (stripMat.HasProperty("_BaseMap"))
            stripMat.SetTexture("_BaseMap", Texture2D.blackTexture);
        var stripMR = strip.GetComponent<MeshRenderer>();
        stripMR.sharedMaterial     = stripMat;
        stripMR.shadowCastingMode  = UnityEngine.Rendering.ShadowCastingMode.Off;
        stripMR.enabled            = false;
        m_Strip    = stripMR;
        m_StripMat = stripMat;

        // Dark copy slightly offset — keeps text legible over bright or busy backgrounds.
        var shadow = Instantiate(sub, sub.transform.parent);
        shadow.name = "Subtitle Shadow";
        shadow.transform.localPosition = new Vector3(0.003f, -0.003f, 0.003f);
        shadow.GetComponent<MeshRenderer>().sharedMaterial = OverlayTextMaterial(font, 4095);
        m_SubtitleShadow = shadow.GetComponent<TextMesh>();
        m_SubtitleShadow.color = new Color(0f, 0f, 0f, 0.85f);

        // On a monitor the subtitle is drawn flat on the screen instead (OnGUI below), at full
        // resolution, so the half-resolution PS1 filter and film grain can't blur it.
        if (PlayerRig.DesktopMode)
        {
            sub.SetActive(false);
            shadow.SetActive(false);
            strip.SetActive(false);
        }
        else
        {
            // after the controllers have their newest pose, so the text doesn't trail behind the arm
            Application.onBeforeRender -= PlaceSubtitle; // set up again after a scene reload
            Application.onBeforeRender += PlaceSubtitle;
            PlaceSubtitle();
        }
    }

    void LateUpdate() => PlaceSubtitle();

    void OnDestroy() => Application.onBeforeRender -= PlaceSubtitle;

    /// <summary>
    /// VR: holds the subtitle just above the right forearm, on the side facing your eyes, turned to face you and upright,
    /// so it reads at any arm angle. Raise your arm like checking a watch to read it. With no right controller tracked
    /// it falls back to floating low in front of the eyes.
    /// </summary>
    void PlaceSubtitle()
    {
        if (m_SubtitleRoot == null || PlayerRig.DesktopMode)
            return;
        var head = PlayerRig.Head;
        if (head == null)
            return;
        if (m_RightHand == null)
            m_RightHand = FindRightHand();
        if (m_RightHand == null || !m_RightHand.gameObject.activeInHierarchy)
        {
            m_SubtitleRoot.SetPositionAndRotation(head.TransformPoint(new Vector3(0f, -0.25f, 1f) * k_HeadDepth), head.rotation);
            m_SubtitleRoot.localScale = Vector3.one * k_HeadDepth;
            return;
        }
        // the wrist sits a little behind the controller and the forearm runs back from it (as PlayerBody poses it)
        var wrist = m_RightHand.position - m_RightHand.forward * 0.07f;
        var onArm = wrist - m_RightHand.forward * k_AlongForearm;
        var outward = Vector3.ProjectOnPlane(head.position - onArm, m_RightHand.forward);
        if (outward.sqrMagnitude > 1e-6f)
            onArm += outward.normalized * k_AboveSkin;
        var look = onArm - head.position;
        if (look.sqrMagnitude < 1e-6f)
            look = head.forward;
        m_SubtitleRoot.SetPositionAndRotation(onArm, Quaternion.LookRotation(look, head.up));
        m_SubtitleRoot.localScale = Vector3.one * k_ForearmScale;
    }

    Transform FindRightHand()
    {
        var origin = PlayerRig.Origin;
        if (origin == null)
            return null;
        foreach (var t in origin.GetComponentsInChildren<Transform>())
            if (t.name == "Rigth Hand" || t.name == "Right Hand")
                return t;
        return null;
    }

    /// <summary>Fallback (no right controller): how far the subtitle floats in front of the eyes (metres).</summary>
    const float k_HeadDepth = 1.8f;
    /// <summary>Size of the forearm subtitle: about 90% of the old floating one's apparent size, read at arm's length.</summary>
    const float k_ForearmScale = 0.4f;
    /// <summary>How far up the forearm from the wrist, and how far off the skin toward your eyes (metres).</summary>
    const float k_AlongForearm = 0.12f, k_AboveSkin = 0.05f;
    /// <summary>Characters per subtitle line, and the dark strip's width for that many (at 1 m).</summary>
    const int k_WrapChars = 30;
    const float k_StripWidth = 0.022f * k_WrapChars;

    /// <summary>Copy of the font material that ignores depth, so text is never hidden inside a wall.</summary>
    public static Material OverlayTextMaterial(Font font, int queue)
    {
        var m = new Material(font.material);
        m.SetFloat("unity_GUIZTestMode", (float)UnityEngine.Rendering.CompareFunction.Always);
        m.renderQueue = queue;
        return m;
    }

    /// <summary>True while a voiced line is playing or queued.</summary>
    public static bool IsSpeaking => s_Instance != null && s_Instance.m_Busy;

    AudioSource m_Audio;
    TextMesh m_Subtitle;
    TextMesh m_SubtitleShadow;
    Transform m_SubtitleRoot, m_RightHand;
    MeshRenderer m_Strip;
    Material m_StripMat;
    string m_Text = "";
    GUIStyle m_Style;

    // Wraps text at word boundaries so subtitles don't overflow the VR viewport (~40 chars wide).
    static string WrapText(string text, int maxWidth = 40)
    {
        if (string.IsNullOrEmpty(text)) return text;
        var words = text.Split(' ');
        var sb = new System.Text.StringBuilder();
        int lineLen = 0;
        foreach (var w in words)
        {
            if (lineLen > 0 && lineLen + 1 + w.Length > maxWidth) { sb.Append('\n'); lineLen = 0; }
            else if (lineLen > 0)                                  { sb.Append(' ');  lineLen++; }
            sb.Append(w);
            lineLen += w.Length;
        }
        return sb.ToString();
    }

    void SetText(string text)
    {
        m_Text = text ?? "";
        var wrapped = WrapText(m_Text, k_WrapChars);
        if (m_Subtitle != null)       m_Subtitle.text       = wrapped;
        if (m_SubtitleShadow != null) m_SubtitleShadow.text = wrapped;
        // show the dark strip only while text is visible; resize it to fit the line count
        var lines = string.IsNullOrEmpty(wrapped) ? 0 : (wrapped.Split('\n').Length);
        var on = lines > 0;
        if (m_StripMat != null)
            m_StripMat.SetColor("_BaseColor", new Color(0.04f, 0.02f, 0.01f, on ? 0.52f : 0f));
        if (m_Strip != null)
        {
            m_Strip.enabled = on;
            if (on)
            {
                const float lineH = 0.072f; // world height per wrapped line at 1 m
                var h = lines * lineH + 0.012f;
                m_Strip.transform.localScale = new Vector3(k_StripWidth, h, 1f);
            }
        }
    }

    void OnGUI()
    {
        if (!PlayerRig.DesktopMode || string.IsNullOrEmpty(m_Text))
            return;
        if (m_Style == null)
            m_Style = new GUIStyle(GUI.skin.label) { alignment = TextAnchor.LowerCenter, wordWrap = true, fontStyle = FontStyle.Bold };
        m_Style.fontSize = Mathf.Max(18, Screen.height / 28); // smaller than before
        var w = Screen.width * 0.72f;
        var r = new Rect((Screen.width - w) / 2f, Screen.height * 0.77f, w, Screen.height * 0.16f);
        // dark background box (cinema-style)
        GUI.color = new Color(0.04f, 0.02f, 0.01f, 0.55f);
        GUI.DrawTexture(new Rect(r.x - 10f, r.y - 6f, r.width + 20f, r.height + 12f), Texture2D.whiteTexture);
        // shadow pass
        GUI.color = new Color(0f, 0f, 0f, 0.8f);
        GUI.Label(new Rect(r.x + 3f, r.y + 3f, r.width, r.height), m_Text, m_Style);
        // text
        GUI.color = new Color(0.95f, 0.88f, 0.65f, 1f);
        GUI.Label(r, m_Text, m_Style);
    }

    /// <summary>Shows a literal hint string as a timed subtitle (no voice clip).</summary>
    IEnumerator ShowHint(string text)
    {
        Setup();
        SetText(text);
        yield return new WaitForSeconds(Mathf.Max(3f, 1f + text.Length * 0.065f));
        if (m_Text == text) // a newer line or hint took over: leave it up
            SetText("");
    }

    string m_Current;
    bool m_Cut;
    readonly List<Behaviour> m_LockedProviders = new List<Behaviour>();

    IEnumerator Run()
    {
        m_Busy = true;
        Setup();
        while (m_Queue.Count > 0)
        {
            var id = m_Queue.Dequeue();
            if (IsStale(id))
                continue;
            m_Current = id;
            m_Cut = false;
            Lines.TryGetValue(id, out var text);
            var clip = useRecordedVoice ? Resources.Load<AudioClip>("Narration/" + id) : null;
            var duration = clip != null ? clip.length : Mathf.Max(3f, 1f + (text ?? "").Length * 0.065f);
            if (clip != null && m_Audio != null)
                m_Audio.PlayOneShot(clip);
            if (showNarrationSubtitles)
                SetText(text);
            SetMovementLock(CurrentStage == 1 && FreezeLines.Contains(id));
            for (var t = 0f; t < duration + 0.3f && !m_Cut; t += Time.deltaTime)
                yield return null;
            if (m_Cut && m_Audio != null)
                m_Audio.Stop();
            SetMovementLock(false);
            m_Current = null;
            SetText("");
            yield return new WaitForSeconds(0.25f);
        }
        m_Busy = false;
    }

    /// <summary>Holds the player before a line starts (e.g. from the first frame until the opening line).
    /// Released automatically when the next voiced line finishes.</summary>
    public static void HoldPlayer() => Instance.SetMovementLock(true);

    /// <summary>Holds the player in place: desktop WASD is ignored, VR move/teleport/jump providers are switched off. Turning still works.</summary>
    void SetMovementLock(bool locked)
    {
        if (PlayerRig.MovementLocked == locked)
            return;
        PlayerRig.MovementLocked = locked;
        if (locked)
        {
            foreach (var p in FindObjectsByType<UnityEngine.XR.Interaction.Toolkit.Locomotion.LocomotionProvider>(FindObjectsSortMode.None))
            {
                var blocks = p is UnityEngine.XR.Interaction.Toolkit.Locomotion.Movement.ContinuousMoveProvider
                          || p is UnityEngine.XR.Interaction.Toolkit.Locomotion.Teleportation.TeleportationProvider
                          || p is UnityEngine.XR.Interaction.Toolkit.Locomotion.Jump.JumpProvider;
                if (blocks && p.enabled)
                {
                    p.enabled = false;
                    m_LockedProviders.Add(p);
                }
            }
        }
        else
        {
            foreach (var p in m_LockedProviders)
                if (p != null) p.enabled = true;
            m_LockedProviders.Clear();
        }
    }

    void OnDisable() => SetMovementLock(false);
}